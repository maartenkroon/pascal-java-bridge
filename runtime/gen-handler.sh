#!/usr/bin/env bash
# Compiles PascalInvocationHandler.java and writes its bytecode as a Pascal include file
# (JavaBridgeHandler.inc) that JavaBridge.pas embeds. Run after changing the Java source.
set -euo pipefail
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
javac --release 17 -d "$tmp" java/pascaljavabridge/internal/PascalInvocationHandler.java
python3 - "$tmp" > JavaBridgeHandler.inc <<'EOF'
import sys, os, glob
base = sys.argv[1]
files = sorted(glob.glob(os.path.join(base, 'pascaljavabridge/internal/*.class')), key=lambda f: (len(f), f))  # outer class first
print('{ Generated by gen-handler.sh from java/pascaljavabridge/internal/PascalInvocationHandler.java - do not edit. }')
print('const')
print('  HANDLER_CLASS_COUNT = %d;' % len(files))
for n, f in enumerate(files):
    data = open(f, 'rb').read()
    name = os.path.relpath(f, base)[:-len('.class')]
    print("  HANDLER_NAME_%d: PAnsiChar = '%s';" % (n, name))
    print('  HANDLER_BYTES_%d: array[0..%d] of Byte = (' % (n, len(data) - 1))
    for i in range(0, len(data), 20):
        chunk = ', '.join('$%02X' % b for b in data[i:i + 20])
        print('    ' + chunk + (',' if i + 20 < len(data) else ''))
    print('  );')
EOF
echo "Wrote $(pwd)/JavaBridgeHandler.inc"
