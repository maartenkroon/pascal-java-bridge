package pascaljavabridge.build;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Stream;

/**
 * Build-time tool: writes the bytecode of the classes in {@code pascaljavabridge/internal} as a
 * Pascal include file ({@code JavaBridgeHandler.inc}) that {@code JavaBridge.pas} embeds and
 * defines in the JVM at runtime. The file is only rewritten when its content changes.
 *
 * <p>Usage: {@code HandlerIncludeWriter <classes-dir> <output.inc>}
 */
public final class HandlerIncludeWriter {

    private HandlerIncludeWriter() {
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            System.err.println("usage: HandlerIncludeWriter <classes-dir> <output.inc>");
            System.exit(2);
        }
        Path classes = Path.of(args[0]);
        Path out = Path.of(args[1]);
        List<Path> files = new ArrayList<>();
        try (Stream<Path> s = Files.list(classes.resolve("pascaljavabridge/internal"))) {
            s.filter(p -> p.toString().endsWith(".class")).forEach(files::add);
        }
        // the outer class first (shortest name), then its nested classes
        files.sort(Comparator.comparingInt((Path p) -> p.toString().length()).thenComparing(Path::toString));

        StringBuilder sb = new StringBuilder();
        sb.append("{ Generated by the pascal-java-bridge-handler Maven module from\n")
          .append("  pascaljavabridge/internal/PascalInvocationHandler.java - do not edit. }\n")
          .append("const\n")
          .append("  HANDLER_CLASS_COUNT = ").append(files.size()).append(";\n");
        for (int n = 0; n < files.size(); n++) {
            Path f = files.get(n);
            byte[] data = Files.readAllBytes(f);
            String rel = classes.relativize(f).toString().replace('\\', '/');
            String name = rel.substring(0, rel.length() - ".class".length());
            sb.append("  HANDLER_NAME_").append(n).append(": PAnsiChar = '").append(name).append("';\n");
            sb.append("  HANDLER_BYTES_").append(n).append(": array[0..").append(data.length - 1)
              .append("] of Byte = (\n");
            for (int i = 0; i < data.length; i += 20) {
                sb.append("    ");
                for (int j = i; j < Math.min(i + 20, data.length); j++) {
                    if (j > i) sb.append(", ");
                    sb.append(String.format("$%02X", data[j] & 0xff));
                }
                sb.append(i + 20 < data.length ? ",\n" : "\n");
            }
            sb.append("  );\n");
        }
        String content = sb.toString();
        if (Files.exists(out) && Files.readString(out, StandardCharsets.UTF_8).equals(content)) {
            System.out.println(out + " is up to date");
            return;
        }
        Files.createDirectories(out.getParent());
        Files.writeString(out, content, StandardCharsets.UTF_8);
        System.out.println("Wrote " + out);
    }
}
